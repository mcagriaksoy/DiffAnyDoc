def default_ai_dir() -> Path:
    """Directory where llamafile and downloaded GGUF models are stored."""
    override = os.environ.get("DIFFANYDOC_AI_DIR")
    if override:
        return Path(override).expanduser()
    if sys.platform == "win32":
        base = Path(os.environ.get("LOCALAPPDATA") or (Path.home() / "AppData" / "Local"))
        return base / "DiffAnyDoc" / "ai"
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "DiffAnyDoc" / "ai"
    base = Path(os.environ.get("XDG_DATA_HOME") or (Path.home() / ".local" / "share"))
    return base / "diffanydoc" / "ai"


def _config_path(ai_dir: Path | None = None) -> Path:
    return (ai_dir or default_ai_dir()) / "config.json"


def load_config(ai_dir: Path | None = None) -> AiConfig:
    path = _config_path(ai_dir)
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(raw, dict):
            return AiConfig(
                preset=str(raw.get("preset") or "qwen-0.5b-q2"),
                custom_endpoint=str(raw.get("custom_endpoint") or "").strip(),
                custom_model=str(raw.get("custom_model") or "").strip(),
                max_tokens=int(raw.get("max_tokens") or 900),
                timeout=float(raw.get("timeout") or 90.0),
            )
    except (OSError, ValueError, TypeError):
        pass
    return AiConfig()


def save_config(config: AiConfig, ai_dir: Path | None = None) -> AiConfig:
    path = _config_path(ai_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(asdict(config), ensure_ascii=False, indent=2), encoding="utf-8")
    return config


def llamafile_binary_path(ai_dir: Path | None = None) -> Path:
    root = ai_dir or default_ai_dir()
    name = "llamafile.exe" if sys.platform == "win32" else "llamafile"
    return root / "bin" / name


def model_file_path(preset: str, ai_dir: Path | None = None) -> Path | None:
    root = ai_dir or default_ai_dir()
    info = MODEL_PRESETS.get(preset)
    if not info:
        return None
    return root / "models" / str(info["filename"])


def is_model_installed(config: AiConfig | None = None, ai_dir: Path | None = None) -> bool:
    cfg = config or load_config(ai_dir)
    if cfg.preset == "custom":
        if cfg.custom_endpoint:
            return True
        if cfg.custom_model:
            p = Path(cfg.custom_model).expanduser()
            if p.is_file():
                if p.suffix.lower() == ".llamafile":
                    return True
                return llamafile_binary_path(ai_dir).is_file() or bool(shutil.which("llamafile"))
        return False

    mpath = model_file_path(cfg.preset, ai_dir)
    if mpath is None or not mpath.is_file() or mpath.stat().st_size < 1024 * 1024:
        return False
    bin_path = llamafile_binary_path(ai_dir)
    return (bin_path.is_file() and bin_path.stat().st_size > 1024 * 100) or bool(
        shutil.which("llamafile")
    )


