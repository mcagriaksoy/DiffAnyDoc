def default_ai_dir() -> Path:
    """Directory where llamafile and downloaded GGUF models are stored."""
    override = os.environ.get("DIFFANYDOC_AI_DIR")
    if override:
        return Path(override).expanduser()
    if sys.platform == "win32":
        base = Path(os.environ.get("LOCALAPPDATA") or (Path.home() / "AppData" / "Local"))
        return base / "DiffAnyDoc" / "ai"
    if sys.platform == "darwin":
        return Path.home() / "Library" / "Application Support" / "DiffAnyDoc" / "ai"
    base = Path(os.environ.get("XDG_DATA_HOME") or (Path.home() / ".local" / "share"))
    return base / "diffanydoc" / "ai"


def _config_path(ai_dir: Path | None = None) -> Path:
    return (ai_dir or default_ai_dir()) / "config.json"


def load_config(ai_dir: Path | None = None) -> AiConfig:
    path = _config_path(ai_dir)
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
        if isinstance(raw, dict):
            return AiConfig(
                preset=str(raw.get("preset") or "qwen-0.5b-q2"),
                custom_endpoint=str(raw.get("custom_endpoint") or "").strip(),
                custom_model=str(raw.get("custom_model") or "").strip(),
                max_tokens=int(raw.get("max_tokens") or 900),
                timeout=float(raw.get("timeout") or 90.0),
            )
    except (OSError, ValueError, TypeError):
        pass
    return AiConfig()


def save_config(config: AiConfig, ai_dir: Path | None = None) -> AiConfig:
    path = _config_path(ai_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(asdict(config), ensure_ascii=False, indent=2), encoding="utf-8")
    return config


def llamafile_binary_path(ai_dir: Path | None = None) -> Path:
    root = ai_dir or default_ai_dir()
    name = "llamafile.exe" if sys.platform == "win32" else "llamafile"
    return root / "bin" / name


def model_file_path(preset: str, ai_dir: Path | None = None) -> Path | None:
    root = ai_dir or default_ai_dir()
    info = MODEL_PRESETS.get(preset)
    if not info:
        return None
    return root / "models" / str(info["filename"])


def is_model_installed(config: AiConfig | None = None, ai_dir: Path | None = None) -> bool:
    cfg = config or load_config(ai_dir)
    if cfg.preset == "custom":
        if cfg.custom_endpoint:
            return True
        if cfg.custom_model:
            p = Path(cfg.custom_model).expanduser()
            if p.is_file():
                if p.suffix.lower() == ".llamafile":
                    return True
                return llamafile_binary_path(ai_dir).is_file() or bool(shutil.which("llamafile"))
        return False

    mpath = model_file_path(cfg.preset, ai_dir)
    if mpath is None or not mpath.is_file() or mpath.stat().st_size < 1024 * 1024:
        return False
    bin_path = llamafile_binary_path(ai_dir)
    return (bin_path.is_file() and bin_path.stat().st_size > 1024 * 100) or bool(
        shutil.which("llamafile")
    )


# --------------------------------------------------------------------------- #
# Background Downloader for llamafile + GGUF model
# --------------------------------------------------------------------------- #

_DOWNLOAD_LOCK = threading.Lock()
_DOWNLOAD_STATE: dict[str, Any] = {
    "status": "idle",  # "idle" | "downloading" | "completed" | "cancelled" | "error"
    "preset": "qwen-0.5b-q2",
    "stage": "",
    "downloaded_bytes": 0,
    "total_bytes": 0,
    "percent": 0.0,
    "error": None,
}
_CANCEL_EVENT = threading.Event()


def download_status() -> dict[str, Any]:
    with _DOWNLOAD_LOCK:
        return dict(_DOWNLOAD_STATE)


def cancel_download() -> dict[str, Any]:
    _CANCEL_EVENT.set()
    with _DOWNLOAD_LOCK:
        if _DOWNLOAD_STATE["status"] == "downloading":
            _DOWNLOAD_STATE["status"] = "cancelled"
        return dict(_DOWNLOAD_STATE)


def _download_file(url: str, dest: Path, stage_name: str, base_done: int, grand_total: int) -> int:
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp_file = dest.with_suffix(dest.suffix + ".part")
    req = Request(url, headers={"User-Agent": "DiffAnyDoc-LocalAI/1.0"})
    done = base_done
    with urlopen(req, timeout=30.0) as resp:
        content_len = int(resp.headers.get("Content-Length") or 0)
        total = grand_total if grand_total > 0 else content_len
        with tmp_file.open("wb") as out:
            while True:
                if _CANCEL_EVENT.is_set():
                    raise AiError("Download cancelled")
                chunk = resp.read(256 * 1024)
                if not chunk:
                    break
                out.write(chunk)
                done += len(chunk)
                with _DOWNLOAD_LOCK:
                    _DOWNLOAD_STATE["stage"] = stage_name
                    _DOWNLOAD_STATE["downloaded_bytes"] = done
                    if total > 0:
                        _DOWNLOAD_STATE["total_bytes"] = total
                        _DOWNLOAD_STATE["percent"] = round(min(99.9, (done * 100.0) / total), 1)
    os.replace(tmp_file, dest)
    return done


def start_download(preset: str = "qwen-0.5b-q2", ai_dir: Path | None = None) -> dict[str, Any]:
    """Start downloading llamafile and the requested GGUF preset in a background thread."""
    if preset not in MODEL_PRESETS:
        raise AiError(f"Unknown model preset: {preset}")

    with _DOWNLOAD_LOCK:
        if _DOWNLOAD_STATE["status"] == "downloading":
            return dict(_DOWNLOAD_STATE)
        _CANCEL_EVENT.clear()
        info = MODEL_PRESETS[preset]
        est_total = int(info["size_mb"]) * 1024 * 1024 + (38 * 1024 * 1024)
        _DOWNLOAD_STATE.update(
            {
                "status": "downloading",
                "preset": preset,
                "stage": "llamafile",
                "downloaded_bytes": 0,
                "total_bytes": est_total,
                "percent": 0.0,
                "error": None,
            }
        )

    def _worker() -> None:
        try:
            done_bytes = 0
            with _DOWNLOAD_LOCK:
                est = int(_DOWNLOAD_STATE["total_bytes"])
            bin_dest = llamafile_binary_path(ai_dir)
            if not (bin_dest.is_file() and bin_dest.stat().st_size > 1024 * 100) and not shutil.which(
                "llamafile"
            ):
                done_bytes = _download_file(LLAMAFILE_URL, bin_dest, "llamafile", done_bytes, est)
                if sys.platform != "win32":
                    current_mode = bin_dest.stat().st_mode
                    bin_dest.chmod(current_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

            m_dest = model_file_path(preset, ai_dir)
            assert m_dest is not None
            info = MODEL_PRESETS[preset]
            if not (m_dest.is_file() and m_dest.stat().st_size > 1024 * 1024):
                done_bytes = _download_file(
                    str(info["url"]),
                    m_dest,
                    str(info["filename"]),
                    done_bytes,
                    est,
                )

            cfg = load_config(ai_dir)
            cfg.preset = preset
            save_config(cfg, ai_dir)

            with _DOWNLOAD_LOCK:
                _DOWNLOAD_STATE.update(
                    {
                        "status": "completed",
                        "stage": "ready",
                        "downloaded_bytes": done_bytes,
                        "percent": 100.0,
                        "error": None,
                    }
                )
        except Exception as exc:
            with _DOWNLOAD_LOCK:
                if _CANCEL_EVENT.is_set():
                    _DOWNLOAD_STATE["status"] = "cancelled"
                    _DOWNLOAD_STATE["error"] = None
                else:
                    _DOWNLOAD_STATE["status"] = "error"
                    _DOWNLOAD_STATE["error"] = str(exc)

    threading.Thread(target=_worker, daemon=True, name="diffanydoc-ai-dl").start()
    return download_status()


# --------------------------------------------------------------------------- #
# Managed llamafile Sidecar Process
# --------------------------------------------------------------------------- #

_SERVER_LOCK = threading.Lock()
_SERVER_PROC: subprocess.Popen[bytes] | None = None
_SERVER_PORT: int | None = None
_SERVER_MODEL_KEY: str | None = None


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _subprocess_flags() -> int:
    if sys.platform == "win32":
        return int(getattr(subprocess, "CREATE_NO_WINDOW", 0))
    return 0


def _local_opener():
    return build_opener(ProxyHandler({}))


def _ping_endpoint(base_url: str, timeout: float = 1.5) -> bool:
    opener = _local_opener()
    for suffix in ("/models", "/health"):
        try:
            url = base_url.rstrip("/") + suffix
            with opener.open(url, timeout=timeout) as resp:
                if resp.status == 200:
                    return True
        except Exception:
            continue
    return False


def stop_server() -> None:
    """Stop the managed background llamafile server if running."""
    global _SERVER_PROC, _SERVER_PORT, _SERVER_MODEL_KEY
    with _SERVER_LOCK:
        if _SERVER_PROC is not None:
            try:
                _SERVER_PROC.terminate()
                _SERVER_PROC.wait(timeout=3.0)
            except Exception:
                try:
                    _SERVER_PROC.kill()
                except Exception:
                    pass
            _SERVER_PROC = None
            _SERVER_PORT = None
            _SERVER_MODEL_KEY = None


def ensure_server_running(
    config: AiConfig | None = None, ai_dir: Path | None = None
) -> tuple[str, str]:
    """Return ``(api_base_url, model_label)`` for the active AI engine, starting llamafile if needed."""
    global _SERVER_PROC, _SERVER_PORT, _SERVER_MODEL_KEY
    cfg = config or load_config(ai_dir)

    if cfg.preset == "custom" and cfg.custom_endpoint:
        endpoint = cfg.custom_endpoint.rstrip("/")
        if not endpoint.endswith("/v1"):
            endpoint = endpoint + "/v1"
        return endpoint, (cfg.custom_model or "local-model")

    # Determine binary and model path
    bin_path = llamafile_binary_path(ai_dir)
    if not bin_path.is_file():
        which_bin = shutil.which("llamafile")
        if which_bin:
            bin_path = Path(which_bin)

    if cfg.preset == "custom" and cfg.custom_model:
        custom_path = Path(cfg.custom_model).expanduser()
        if not custom_path.is_file():
            raise AiError(f"Model file not found: {custom_path}")
        if custom_path.suffix.lower() == ".llamafile":
            cmd_prefix = [str(custom_path)]
            model_key = str(custom_path)
            model_label = custom_path.name
        else:
            if not bin_path.is_file():
                raise AiError("llamafile binary is not installed yet.")
            cmd_prefix = [str(bin_path), "-m", str(custom_path)]
            model_key = f"{bin_path}:{custom_path}"
            model_label = custom_path.name
    else:
        mpath = model_file_path(cfg.preset, ai_dir)
        if mpath is None or not mpath.is_file():
            raise AiError(f"Model '{cfg.preset}' is not downloaded yet.")
        if not bin_path.is_file():
            raise AiError("llamafile binary is not installed yet.")
        cmd_prefix = [str(bin_path), "-m", str(mpath)]
        model_key = f"{bin_path}:{mpath}"
        model_label = str(MODEL_PRESETS[cfg.preset]["name"])

    with _SERVER_LOCK:
        if (
            _SERVER_PROC is not None
            and _SERVER_PROC.poll() is None
            and _SERVER_PORT is not None
            and _SERVER_MODEL_KEY == model_key
        ):
            base_url = f"http://127.0.0.1:{_SERVER_PORT}/v1"
            if _ping_endpoint(base_url, timeout=1.0):
                return base_url, model_label

    stop_server()

    with _SERVER_LOCK:
        port = _free_port()
        cmd = [
            *cmd_prefix,
            "--server",
            "--nobrowser",
            "--host",
            "127.0.0.1",
            "--port",
            str(port),
            "-c",
            "4096",
        ]
        # On Unix, llamafile is an APE polyglot that can be invoked via sh if binfmt_misc blocks direct exec
        try:
            proc = subprocess.Popen(
                cmd,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                creationflags=_subprocess_flags(),
            )
        except OSError:
            if sys.platform != "win32":
                proc = subprocess.Popen(
                    ["/bin/sh", *cmd],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.PIPE,
                )
            else:
                raise

        _SERVER_PROC = proc
        _SERVER_PORT = port
        _SERVER_MODEL_KEY = model_key
        base_url = f"http://127.0.0.1:{port}/v1"

    deadline = time.monotonic() + 30.0
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            err = ""
            if proc.stderr:
                try:
                    err = proc.stderr.read().decode("utf-8", "replace")[-400:].strip()
                except Exception:
                    pass
            raise AiError(f"llamafile exited unexpectedly: {err or proc.returncode}")
        if _ping_endpoint(base_url, timeout=1.0):
            return base_url, model_label
        time.sleep(0.15)

    raise AiError("Timed out waiting for local llamafile server to become ready.")


def get_status(ai_dir: Path | None = None) -> dict[str, Any]:
    """Return full status dictionary for the UI and Settings dialog."""
    root = ai_dir or default_ai_dir()
    cfg = load_config(root)
    installed = is_model_installed(cfg, root)
    bin_path = llamafile_binary_path(root)
    llamafile_installed = (bin_path.is_file() and bin_path.stat().st_size > 1024 * 100) or bool(
        shutil.which("llamafile")
    )
    running = False
    with _SERVER_LOCK:
        if _SERVER_PROC is not None and _SERVER_PROC.poll() is None and _SERVER_PORT is not None:
            running = True
    presets = []
    for key, info in MODEL_PRESETS.items():
        mpath = model_file_path(key, root)
        presets.append(
            {
                **info,
                "installed": bool(mpath and mpath.is_file() and mpath.stat().st_size > 1024 * 1024),
            }
        )
    dl = download_status()
    dl["active"] = dl.get("status") == "downloading"
    if cfg.preset in MODEL_PRESETS:
        active_label = str(MODEL_PRESETS[cfg.preset]["name"])
    else:
        active_label = cfg.custom_model or cfg.custom_endpoint or "Custom Local Model"
    return {
        "config": asdict(cfg),
        "installed": installed,
        "available": installed,
        "llamafile_installed": llamafile_installed,
        "active_model_label": active_label,
        "ai_dir": str(root),
        "running": running,
        "presets": presets,
        "download": dl,
    }


