class AiError(RuntimeError):
    """Local AI engine could not complete the request."""


@dataclass(slots=True)
class AiConfig:
    """User-configurable settings for the local AI engine."""

    #: Preset key in ``MODEL_PRESETS`` or ``"custom"``.
    preset: str = "qwen-0.5b-q2"
    #: Optional OpenAI-compatible base URL (e.g. ``http://127.0.0.1:8080/v1``).
    custom_endpoint: str = ""
    #: Optional custom ``.gguf`` / ``.llamafile`` file path or remote model tag.
    custom_model: str = ""
    #: Max tokens generated by the semantic summary.
    max_tokens: int = 900
    #: Request timeout in seconds.
    timeout: float = 90.0


@dataclass(slots=True)
class AiFinding:
    """One numbered semantic finding produced by the AI comparison."""

    id: int
    category: str  # "content" | "rewording" | "layout"
    title: str
    explanation: str
    page: int = 1
    row: int = -1
    left_text: str = ""
    right_text: str = ""

    def as_dict(self) -> dict[str, Any]:
        return asdict(self)


@dataclass(slots=True)
class AiAnalysisResult:
    """Structured result of an AI semantic document comparison."""

    summary: str
    verdict: str  # "identical_meaning" | "layout_only" | "minor_changes" | "major_changes"
    items: list[AiFinding] = field(default_factory=list)
    model: str = ""
    elapsed_ms: int = 0

    def as_dict(self) -> dict[str, Any]:
        return {
            "summary": self.summary,
            "verdict": self.verdict,
            "items": [item.as_dict() for item in self.items],
            "model": self.model,
            "elapsed_ms": self.elapsed_ms,
        }


