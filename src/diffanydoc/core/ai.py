def build_comparison_digest(result: DiffResult, max_items: int = 28) -> list[dict[str, Any]]:
    """Extract a compact, numbered list of changed or shifted blocks from ``result``."""
    digest: list[dict[str, Any]] = []
    seq = 1
    for row_idx, row in enumerate(result.rows):
        a = row.left
        b = row.right
        shift_meta = (
            (b.style.get("position_shift") if b and b.style else None)
            or (a.style.get("position_shift") if a and a.style else None)
        )
        has_inline_diff = bool(
            (row.left_inline and any(s.kind != "equal" for s in row.left_inline))
            or (row.right_inline and any(s.kind != "equal" for s in row.right_inline))
        )
        is_shift_only = bool(shift_meta and not has_inline_diff and a and b)

        if row.kind == "equal" and not shift_meta and not row.format_changes:
            continue

        page_num = (b.page + 1) if b is not None else ((a.page + 1) if a is not None else 1)
        left_txt = (a.text.strip()[:220] if a and a.text else "")
        right_txt = (b.text.strip()[:220] if b and b.text else "")
        if not left_txt and not right_txt:
            continue

        kind_tag = (
            "position_shift_only"
            if is_shift_only
            else ("added" if row.kind == "insert" else ("removed" if row.kind == "delete" else "modified"))
        )
        item_id = int(shift_meta["id"]) if (shift_meta and shift_meta.get("id")) else seq
        seq = max(seq + 1, item_id + 1)

        entry: dict[str, Any] = {
            "id": item_id,
            "row": row_idx,
            "page": page_num,
            "type": kind_tag,
            "left": left_txt,
            "right": right_txt,
        }
        if shift_meta:
            entry["shift"] = shift_meta.get("label", "")
        digest.append(entry)
        if len(digest) >= max_items:
            break
    return digest


def _chat_completion(
    base_url: str,
    model_name: str,
    messages: list[dict[str, str]],
    *,
    max_tokens: int = 900,
    timeout: float = 90.0,
) -> str:
    url = base_url.rstrip("/") + "/chat/completions"
    payload = {
        "model": model_name,
        "messages": messages,
        "temperature": 0.1,
        "max_tokens": max_tokens,
        "stream": False,
    }
    data = json.dumps(payload, ensure_ascii=False).encode("utf-8")
    req = Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    parsed = urlparse(url)
    use_no_proxy = parsed.hostname in ("127.0.0.1", "localhost", "::1")
    opener = _local_opener() if use_no_proxy else build_opener()
    try:
        with opener.open(req, timeout=timeout) as resp:
            body = json.loads(resp.read().decode("utf-8", "replace"))
    except HTTPError as exc:
        detail = exc.read().decode("utf-8", "replace")[:300]
        raise AiError(f"AI server HTTP {exc.code}: {detail}") from exc
    except (URLError, OSError, TimeoutError) as exc:
        raise AiError(f"Could not connect to local AI server ({url}): {exc}") from exc

    try:
        choices = body.get("choices") or []
        content = choices[0]["message"]["content"]
        return str(content or "").strip()
    except (KeyError, IndexError, TypeError) as exc:
        raise AiError(f"Unexpected AI response format: {body}") from exc


def _extract_json_object(raw: str) -> dict[str, Any] | None:
    cleaned = re.sub(r"<think>.*?</think>", "", raw, flags=re.DOTALL).strip()
    fence = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", cleaned, re.DOTALL)
    if fence:
        cleaned = fence.group(1)
    else:
        start = cleaned.find("{")
        end = cleaned.rfind("}")
        if start != -1 and end != -1 and end > start:
            cleaned = cleaned[start : end + 1]
    try:
        parsed = json.loads(cleaned)
        if isinstance(parsed, dict):
            return parsed
    except ValueError:
        return None
    return None


def analyze_comparison(
    result: DiffResult,
    language: str = "tr",
    *,
    config: AiConfig | None = None,
    ai_dir: Path | None = None,
) -> AiAnalysisResult:
    """Run local AI semantic analysis on a ``DiffResult``."""
    started = time.monotonic()
    cfg = config or load_config(ai_dir)
    digest = build_comparison_digest(result)

    is_tr = str(language).lower().startswith("tr")
    if not digest:
        summary = (
            "İki belge arasında hiçbir metin veya konum farkı tespit edilmedi; belgeler anlamsal ve görsel olarak birebir aynıdır."
            if is_tr
            else "No text or layout differences were found between the two documents; they are semantically and visually identical."
        )
        return AiAnalysisResult(
            summary=summary,
            verdict="identical_meaning",
            items=[],
            model=cfg.preset,
            elapsed_ms=int((time.monotonic() - started) * 1000),
        )

    base_url, model_label = ensure_server_running(cfg, ai_dir)

    lang_instruction = (
        "Yanıtını tamamen TÜRKÇE olarak ver."
        if is_tr
        else "Respond entirely in ENGLISH."
    )
    system_prompt = (
        "You are a precise document comparison analyst. "
        "Given a structured list of differences and position shifts between Document A (Left) and Document B (Right), "
        "distinguish between pure layout/position shifts (where the text is identical but moved on the page) "
        "and real content/value changes. "
        f"{lang_instruction} "
        "Return ONLY valid JSON matching this schema:\n"
        "{\n"
        '  "summary": "2-3 sentence executive summary of what changed",\n'
        '  "verdict": "layout_only | minor_changes | major_changes | identical_meaning",\n'
        '  "items": [\n'
        "    {\n"
        '      "id": 1,\n'
        '      "category": "content | rewording | layout",\n'
        '      "title": "Short title",\n'
        '      "explanation": "Clear explanation of the difference or shift"\n'
        "    }\n"
        "  ]\n"
        "}"
    )

    user_payload = {
        "document_a": Path(result.left_path).name,
        "document_b": Path(result.right_path).name,
        "similarity_pct": round(result.stats.similarity * 100, 1),
        "differences": digest,
    }
    messages = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": json.dumps(user_payload, ensure_ascii=False)},
    ]

    raw_reply = _chat_completion(
        base_url,
        cfg.custom_model or model_label,
        messages,
        max_tokens=cfg.max_tokens,
        timeout=cfg.timeout,
    )

    by_id = {int(d["id"]): d for d in digest}
    parsed = _extract_json_object(raw_reply)
    findings: list[AiFinding] = []

    if parsed:
        summary = str(parsed.get("summary") or "").strip()
        verdict = str(parsed.get("verdict") or "minor_changes").strip()
        if verdict not in ("identical_meaning", "layout_only", "minor_changes", "major_changes"):
            verdict = "minor_changes"
        raw_items = parsed.get("items")
        if isinstance(raw_items, list):
            for idx, item in enumerate(raw_items, start=1):
                if not isinstance(item, dict):
                    continue
                fid = int(item.get("id") or idx)
                src = by_id.get(fid) or (digest[idx - 1] if idx - 1 < len(digest) else {})
                cat = str(item.get("category") or "").strip().lower()
                if cat not in ("content", "rewording", "layout"):
                    cat = "layout" if src.get("type") == "position_shift_only" else "content"
                findings.append(
                    AiFinding(
                        id=fid,
                        category=cat,
                        title=str(item.get("title") or f"#{fid}"),
                        explanation=str(item.get("explanation") or ""),
                        page=int(src.get("page") or 1),
                        row=int(src.get("row") if src.get("row") is not None else -1),
                        left_text=str(src.get("left") or ""),
                        right_text=str(src.get("right") or ""),
                    )
                )
    else:
        summary = raw_reply[:600]
        all_shifts = all(d.get("type") == "position_shift_only" for d in digest)
        verdict = "layout_only" if all_shifts else "minor_changes"

    if not findings:
        for d in digest:
            is_shift = d.get("type") == "position_shift_only"
            fid = int(d["id"])
            shift_str = d.get("shift") or ""
            if is_shift:
                title = (
                    f"#{fid} Konum Kayması ({shift_str})"
                    if is_tr
                    else f"#{fid} Position Shift ({shift_str})"
                )
                expl = (
                    f"Metin her iki belgede de birebir aynıdır, yalnızca sayfadaki konumu değişmiştir ({shift_str})."
                    if is_tr
                    else f"The text is identical in both documents; only its position on the page shifted ({shift_str})."
                )
                cat = "layout"
            else:
                title = f"#{fid} İçerik Farkı" if is_tr else f"#{fid} Content Difference"
                expl = (
                    f"Sol: '{d.get('left')}' → Sağ: '{d.get('right')}'"
                    if is_tr
                    else f"Left: '{d.get('left')}' → Right: '{d.get('right')}'"
                )
                cat = "content"
            findings.append(
                AiFinding(
                    id=fid,
                    category=cat,
                    title=title,
                    explanation=expl,
                    page=int(d.get("page") or 1),
                    row=int(d.get("row") if d.get("row") is not None else -1),
                    left_text=str(d.get("left") or ""),
                    right_text=str(d.get("right") or ""),
                )
            )

    if not summary:
        only_layout = all(f.category == "layout" for f in findings)
        summary = (
            "İki belgedeki tüm metinler eşleşmektedir; tespit edilen farklar yalnızca sayfa düzeni ve konum kaymalarından ibarettir."
            if (only_layout and is_tr)
            else (
                "All texts match across both documents; the detected differences are purely layout and position shifts."
                if only_layout
                else (
                    f"Toplam {len(findings)} maddede fark veya konum değişimi incelendi."
                    if is_tr
                    else f"Analyzed {len(findings)} differences and layout shifts across the documents."
                )
            )
        )

    elapsed_ms = int((time.monotonic() - started) * 1000)
    analysis_res = AiAnalysisResult(
        summary=summary,
        verdict=verdict,
        items=findings,
        model=model_label,
        elapsed_ms=elapsed_ms,
    )
    result.ai_analysis = analysis_res.as_dict()
    return analysis_res


def explain_row_with_ai(
    result: DiffResult,
    row_index: int,
    language: str = "tr",
    *,
    config: AiConfig | None = None,
    ai_dir: Path | None = None,
) -> AiFinding:
    """Explain a single row difference or layout shift using the local AI engine."""
    if row_index < 0 or row_index >= len(result.rows):
        raise AiError(f"Row index out of range: {row_index}")

    row = result.rows[row_index]
    a = row.left
    b = row.right
    left_txt = (a.text.strip() if a and a.text else "")
    right_txt = (b.text.strip() if b and b.text else "")
    shift_meta = (
        (b.style.get("position_shift") if b and b.style else None)
        or (a.style.get("position_shift") if a and a.style else None)
    )
    page_num = (b.page + 1) if b is not None else ((a.page + 1) if a is not None else 1)
    item_id = int(shift_meta["id"]) if (shift_meta and shift_meta.get("id")) else (row_index + 1)

    cfg = config or load_config(ai_dir)
    base_url, model_label = ensure_server_running(cfg, ai_dir)
    is_tr = str(language).lower().startswith("tr")
    lang_instruction = (
        "Yanıtını tamamen TÜRKÇE olarak ver."
        if is_tr
        else "Respond entirely in ENGLISH."
    )

    system_prompt = (
        "You are a precise document comparison assistant. "
        "Explain the difference or layout shift for this single row in 1-2 concise sentences. "
        f"{lang_instruction} "
        "Return ONLY valid JSON:\n"
        "{\n"
        '  "category": "content | rewording | layout",\n'
        '  "title": "Short title",\n'
        '  "explanation": "1-2 sentence explanation"\n'
        "}"
    )
    user_payload = {
        "row": row_index,
        "page": page_num,
        "kind": row.kind,
        "left": left_txt[:400],
        "right": right_txt[:400],
        "position_shift": shift_meta.get("label") if shift_meta else None,
    }
    raw_reply = _chat_completion(
        base_url,
        cfg.custom_model or model_label,
        [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": json.dumps(user_payload, ensure_ascii=False)},
        ],
        max_tokens=260,
        timeout=cfg.timeout,
    )
    parsed = _extract_json_object(raw_reply)
    if parsed:
        cat = str(parsed.get("category") or "").strip().lower()
        if cat not in ("content", "rewording", "layout"):
            cat = "layout" if (shift_meta and left_txt == right_txt) else "content"
        title = str(parsed.get("title") or f"#{item_id}").strip()
        explanation = str(parsed.get("explanation") or raw_reply[:240]).strip()
    else:
        cat = "layout" if (shift_meta and left_txt == right_txt) else "content"
        title = f"#{item_id}"
        explanation = raw_reply.strip()[:280]

    finding = AiFinding(
        id=item_id,
        category=cat,
        title=title,
        explanation=explanation,
        page=page_num,
        row=row_index,
        left_text=left_txt[:220],
        right_text=right_txt[:220],
    )
    return finding
