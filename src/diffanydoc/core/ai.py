# Managed llamafile Sidecar Process
# --------------------------------------------------------------------------- #

_SERVER_LOCK = threading.Lock()
_SERVER_PROC: subprocess.Popen[bytes] | None = None
_SERVER_PORT: int | None = None
_SERVER_MODEL_KEY: str | None = None


def _free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _subprocess_flags() -> int:
    if sys.platform == "win32":
        return int(getattr(subprocess, "CREATE_NO_WINDOW", 0))
    return 0


def _local_opener():
    return build_opener(ProxyHandler({}))


def _ping_endpoint(base_url: str, timeout: float = 1.5) -> bool:
    opener = _local_opener()
    for suffix in ("/models", "/health"):
        try:
            url = base_url.rstrip("/") + suffix
            with opener.open(url, timeout=timeout) as resp:
                if resp.status == 200:
                    return True
        except Exception:
            continue
    return False


def stop_server() -> None:
    """Stop the managed background llamafile server if running."""
    global _SERVER_PROC, _SERVER_PORT, _SERVER_MODEL_KEY
    with _SERVER_LOCK:
        if _SERVER_PROC is not None:
            try:
                _SERVER_PROC.terminate()
                _SERVER_PROC.wait(timeout=3.0)
            except Exception:
                try:
                    _SERVER_PROC.kill()
                except Exception:
                    pass
            _SERVER_PROC = None
            _SERVER_PORT = None
            _SERVER_MODEL_KEY = None


def ensure_server_running(
    config: AiConfig | None = None, ai_dir: Path | None = None
) -> tuple[str, str]:
    """Return ``(api_base_url, model_label)`` for the active AI engine, starting llamafile if needed."""
    global _SERVER_PROC, _SERVER_PORT, _SERVER_MODEL_KEY
    cfg = config or load_config(ai_dir)

    if cfg.preset == "custom" and cfg.custom_endpoint:
        endpoint = cfg.custom_endpoint.rstrip("/")
        if not endpoint.endswith("/v1"):
            endpoint = endpoint + "/v1"
        return endpoint, (cfg.custom_model or "local-model")

    # Determine binary and model path
    bin_path = llamafile_binary_path(ai_dir)
    if not bin_path.is_file():
        which_bin = shutil.which("llamafile")
        if which_bin:
            bin_path = Path(which_bin)

    if cfg.preset == "custom" and cfg.custom_model:
        custom_path = Path(cfg.custom_model).expanduser()
        if not custom_path.is_file():
            raise AiError(f"Model file not found: {custom_path}")
        if custom_path.suffix.lower() == ".llamafile":
            cmd_prefix = [str(custom_path)]
            model_key = str(custom_path)
            model_label = custom_path.name
        else:
            if not bin_path.is_file():
                raise AiError("llamafile binary is not installed yet.")
            cmd_prefix = [str(bin_path), "-m", str(custom_path)]
            model_key = f"{bin_path}:{custom_path}"
            model_label = custom_path.name
    else:
        mpath = model_file_path(cfg.preset, ai_dir)
        if mpath is None or not mpath.is_file():
            raise AiError(f"Model '{cfg.preset}' is not downloaded yet.")
        if not bin_path.is_file():
            raise AiError("llamafile binary is not installed yet.")
        cmd_prefix = [str(bin_path), "-m", str(mpath)]
        model_key = f"{bin_path}:{mpath}"
        model_label = str(MODEL_PRESETS[cfg.preset]["name"])

    with _SERVER_LOCK:
        if (
            _SERVER_PROC is not None
            and _SERVER_PROC.poll() is None
            and _SERVER_PORT is not None
            and _SERVER_MODEL_KEY == model_key
        ):
            base_url = f"http://127.0.0.1:{_SERVER_PORT}/v1"
            if _ping_endpoint(base_url, timeout=1.0):
                return base_url, model_label

    stop_server()

    with _SERVER_LOCK:
        port = _free_port()
        cpu_threads = max(1, min((os.cpu_count() or 4) - 1, 6))
        cmd = [
            *cmd_prefix,
            "--server",
            "--nobrowser",
            "--host",
            "127.0.0.1",
            "--port",
            str(port),
            "-c",
            "2048",
            "-t",
            str(cpu_threads),
        ]
        # On Unix, llamafile is an APE polyglot that can be invoked via sh if binfmt_misc blocks direct exec
        try:
            proc = subprocess.Popen(
                cmd,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                creationflags=_subprocess_flags(),
            )
        except OSError:
            if sys.platform != "win32":
                proc = subprocess.Popen(
                    ["/bin/sh", *cmd],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.PIPE,
                )
            else:
                raise

        _SERVER_PROC = proc
        _SERVER_PORT = port
        _SERVER_MODEL_KEY = model_key
        base_url = f"http://127.0.0.1:{port}/v1"

    deadline = time.monotonic() + 30.0
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            err = ""
            if proc.stderr:
                try:
                    err = proc.stderr.read().decode("utf-8", "replace")[-400:].strip()
                except Exception:
                    pass
            raise AiError(f"llamafile exited unexpectedly: {err or proc.returncode}")
        if _ping_endpoint(base_url, timeout=1.0):
            return base_url, model_label
        time.sleep(0.15)

    raise AiError("Timed out waiting for local llamafile server to become ready.")


def get_status(ai_dir: Path | None = None) -> dict[str, Any]:
    """Return full status dictionary for the UI and Settings dialog."""
    root = ai_dir or default_ai_dir()
    cfg = load_config(root)
    installed = is_model_installed(cfg, root)
    bin_path = llamafile_binary_path(root)
    llamafile_installed = (bin_path.is_file() and bin_path.stat().st_size > 1024 * 100) or bool(
        shutil.which("llamafile")
    )
    running = False
    with _SERVER_LOCK:
        if _SERVER_PROC is not None and _SERVER_PROC.poll() is None and _SERVER_PORT is not None:
            running = True
    presets = []
    for key, info in MODEL_PRESETS.items():
        mpath = model_file_path(key, root)
        presets.append(
            {
                **info,
                "installed": bool(mpath and mpath.is_file() and mpath.stat().st_size > 1024 * 1024),
            }
        )
    dl = download_status()
    dl["active"] = dl.get("status") == "downloading"
    if cfg.preset in MODEL_PRESETS:
        active_label = str(MODEL_PRESETS[cfg.preset]["name"])
    else:
        active_label = cfg.custom_model or cfg.custom_endpoint or "Custom Local Model"
    return {
        "config": asdict(cfg),
        "installed": installed,
        "available": installed,
        "llamafile_installed": llamafile_installed,
        "active_model_label": active_label,
        "ai_dir": str(root),
        "running": running,
        "presets": presets,
        "download": dl,
    }


